pub struct RealTypeFontParser {
    pub data: &'static [u8], // Блин вот так и чешутся у меня руки чтобы сделать этот сранный формат.
} // Да кстати название опять "Реал", я всё так называю и libc(RealAPI) и шрифт.

impl RealTypeFontParser {
    /// Новий парсер
    pub const fn new(data: &'static [u8]) -> Self 
    {
        Self { data }
    }

    /// Извлекание заголовка из начала байтового массива
    pub fn get_header(&self) -> Option<&RTFHeader> 
    {
        if self.data.len() < core::mem::size_of::<RTFHeader>() {
            return None;
        }
        unsafe {
            let header = &*(self.data.as_ptr() as *const RTFHeader);
            if header.magic == RTF_MAGIC {
                Some(header)
            } else {
                None
            }
        }
    }

    pub fn find_glyph(&self, code: u32) -> Option<RTFGlyphMetrics>
    {
        let header = self.get_header()?;
        let glyphs_count = header.glyphs_count as usize;

        let header_size = core::mem::size_of::<RTFHeader>();
        let glyph_size =  core::mem::size_of::<RTFGlyphMetrics>();
        
        let table_start = header_size;
        let table_end   = table_start + (glyphs_count * glyph_size);

        if self.data.len() < table_end { return None; }

        unsafe {
            let glyphs_ptr = self.data.as_ptr().add(table_start) as *const RTFGlyphMetrics;
            let glyphs     = core::slice::from_raw_parts(glyphs_ptr, glyphs_count);


            for glyph in glyphs {
                if glyph.char_code == code { return Some(*glyph); }
            }
        }
        None
    }

    pub fn get_atlas_pixel(&self, x: usize, y: usize) -> u8 
    {
        let header = match self.get_header() {
            Some(h) => h,
            None => return 0,
        };

        let header_size = core::mem::size_of::<RTFHeader>();
        let glyph_size  = core::mem::size_of::<RTFGlyphMetrics>();

        let texture_start = header_size + (header.glyphs_count as usize * glyph_size);
        let pixel_offset  = texture_start + (y * header.atlas_width as usize) + x;

        if pixel_offset < self.data.len() {
            self.data[pixel_offset]
        } else {
            0
        }
    }
}